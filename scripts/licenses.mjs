// Inventory installed npm packages and Cargo's resolved dependency graph.
// Keep upstream license/notice files alongside the inventory for redistribution.
import { readdir, readFile, mkdir, copyFile, writeFile } from 'node:fs/promises'
import { execFileSync } from 'node:child_process'
import { resolve, join, basename } from 'node:path'
const root = resolve(import.meta.dirname, '..')
const out = join(root, 'licenses/third-party')
await mkdir(out, { recursive: true })
const rows = []
async function record(name, version, license, directory, source) {
  const slug = `${name.replace(/[^a-zA-Z0-9._-]/g, '_')}@${version}`
  const files = (await readdir(directory)).filter(f => /^(licen[cs]e|copying|notice)(\.|$|-)/i.test(f))
  await mkdir(join(out, slug), { recursive: true })
  for (const file of files) {
    try { await copyFile(join(directory, file), join(out, slug, basename(file))) } catch (error) { if (error.code !== 'EISDIR') throw error }
  }
  rows.push(`| ${name} | ${version} | ${license || 'UNKNOWN — verify before redistribution'} | ${source} | ${files.length ? `[notices](licenses/third-party/${slug})` : 'No root license file; verify upstream'} |`)
}
const seen = new Set()
const store = join(root, 'frontend/node_modules/.pnpm')
for (const directory of await readdir(store)) {
  const modules = join(store, directory, 'node_modules')
  let names; try { names = await readdir(modules) } catch { continue }
  for (const name of names) {
    const scope = join(modules, name)
    const paths = name.startsWith('@') ? (await readdir(scope)).map(n => join(scope, n)) : [scope]
    for (const path of paths) {
      let pkg; try { pkg = JSON.parse(await readFile(join(path, 'package.json'), 'utf8')) } catch { continue }
      const key = `${pkg.name}@${pkg.version}`
      if (seen.has(key)) continue
      seen.add(key)
      await record(pkg.name, pkg.version, typeof pkg.license === 'string' ? pkg.license : JSON.stringify(pkg.license), path, 'npm (installed; includes tooling)')
    }
  }
}
const metadata = JSON.parse(execFileSync('cargo', ['metadata', '--format-version=1'], {cwd: root, encoding: 'utf8', maxBuffer: 20_000_000}))
for (const pkg of metadata.packages.filter(p => p.source)) await record(pkg.name, pkg.version, pkg.license, resolve(pkg.manifest_path, '..'), 'Cargo')
rows.sort()
await writeFile(join(root, 'third-party-license.md'), `# Third-party dependencies\n\nGenerated by \`node scripts/licenses.mjs\`; includes installed frontend tooling and resolved Rust dependencies. SPDX expressions are upstream declarations, not a legal compatibility assessment. Full available upstream root LICENSE/COPYING/NOTICE files are retained under \`licenses/third-party/\`. Review entries without root notices and bundled native/vendored code before distributing binaries.\n\nThe project's own license remains [License](License). Brand assets have separate project-only authorization: [assets/BRAND-USAGE.md](assets/BRAND-USAGE.md). System Git is an external runtime dependency (GPL-2.0-only); it is not bundled here.\n\n| Dependency | Version | Upstream license | Ecosystem | Retained notices |\n| --- | --- | --- | --- | --- |\n${rows.join('\n')}\n`)
console.log(`Inventoried ${rows.length} dependencies`)
