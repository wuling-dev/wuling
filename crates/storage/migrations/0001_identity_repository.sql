-- 原型 ID 继续保留；新记录从各自 identity sequence 分配。
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    username TEXT NOT NULL CHECK (length(username) BETWEEN 1 AND 80),
    password_hash TEXT NOT NULL,
    admin BOOLEAN NOT NULL DEFAULT false,
    active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX users_username_unique ON users (lower(username));

CREATE TABLE repositories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    owner_id BIGINT NOT NULL REFERENCES users(id),
    name TEXT NOT NULL CHECK (name ~ '^[A-Za-z0-9_-]{1,80}$'),
    description TEXT NOT NULL DEFAULT '' CHECK (length(description) <= 2000),
    public BOOLEAN NOT NULL DEFAULT false,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX repositories_name_unique ON repositories (lower(name));
CREATE INDEX repositories_owner ON repositories (owner_id);

CREATE TABLE repository_members (
    repo_id BIGINT NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id),
    role TEXT NOT NULL CHECK (role IN ('reader', 'developer', 'maintainer')),
    PRIMARY KEY (repo_id, user_id)
);
